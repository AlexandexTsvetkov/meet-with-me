package ru.aston.meet.exception;

/**
 * Исключение, выбрасываемое при ошибках, связанных с приглашениями на встречу.
 * <p>
 * Может использоваться для сигнализации о неудачных операциях с приглашениями,
 * например, при повторной отправке приглашения, попытке принять несуществующее приглашение и т.д.
 * </p>
 */
public class InvitationException extends RuntimeException {

    /**
     * Создает новое исключение, связанное с приглашением на встречу, с указанным сообщением.
     *
     * @param message подробное сообщение об ошибке, связанной с приглашением
     */
    public InvitationException(String message) {
        super(message);
    }
}